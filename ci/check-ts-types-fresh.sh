#!/usr/bin/env bash
# The committed @avarok/citadel-protocol-types sources must be exactly what the
# Rust generates.
#
# citadel-protocol-types-ts/src is published to npm from the committed files, and
# nothing regenerated them: a citadel_types change committed without running
# export_ts published nothing new, or published types that disagreed with the
# Rust. Every ts-rs file (the ones carrying its header) is deleted first and then
# regenerated, so a type deleted from the Rust, a new one, a changed field and a
# hand edit all show. The hand-written files (index.ts, helpers.ts, versions.ts)
# carry no header and are left alone.
#
# Judged against the INDEX (the worktree column of `git status --porcelain`), so
# a regenerated and staged change passes before a commit; in CI index == HEAD.
set -euo pipefail
cd "$(dirname "$0")/.."
DIR=citadel-protocol-types-ts/src

grep -l 'generated by \[ts-rs\]' "$DIR"/*.ts | xargs rm -f
(cd citadel_types && cargo run -q --features typescript --bin export_ts > /dev/null)

STALE=$(git status --porcelain -- "$DIR" | grep -v '^. ' || true)
if [ -n "$STALE" ]; then
    echo "::error::citadel-protocol-types-ts/src differs from what citadel_types generates"
    echo "$STALE" | head -50
    echo
    echo "FAIL: run (cd citadel_types && cargo run --features typescript --bin export_ts) and commit citadel-protocol-types-ts/src."
    exit 1
fi
echo "OK: citadel-protocol-types-ts/src is exactly what citadel_types generates."
